package javacore.Cintermediario.Lgenerics.dominio;

public class Carro {
    private String nome;

    public Carro(String nome) {
        this.nome = nome;
    }

    @Override
    public String toString() {
        return "Carro [nome=" + nome + "]";
    }

    
}
// Este arquivo demonstra classe de domínio Carro com nome para exemplos de generics.
